const DICT_MAP = new Map<string, string>(FE_KANJI_DICT);

function escapeRegExp(str: string): string {
  return str.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// Sort compounds by length DESCENDING so longer compounds (e.g. 日本人) always match before subcompounds (e.g. 本人)
const SORTED_DICT_KEYS = [...FE_KANJI_DICT]
  .map(([k]) => k)
  .sort((a, b) => b.length - a.length);

// Match either existing bracket ruby syntax [...] OR any dictionary compound
const DICT_REGEX = new RegExp(
  "(\\[[^\\]]+\\])|(" + SORTED_DICT_KEYS.map((k) => escapeRegExp(k)).join("|") + ")",
  "g"
);

/**
 * Automatically annotates plain Japanese text with bracket furigana syntax: [kanji:furigana]
 * Single-pass regex ignores already bracketed tokens, preventing nested brackets.
 */
export function autoAnnotateRuby(text: string): string {
  if (!text) return "";

  return text.replace(DICT_REGEX, (match, existingBracket, matchedTerm) => {
    if (existingBracket) return match;
    return DICT_MAP.get(matchedTerm) || match;
  });
}

/**
 * Strips all bracket ruby annotations like "[公開鍵:こうかいかぎ]"
 * back into plain text "公開鍵" for speech synthesis (TTS) or search.
 */
export function stripRuby(text: string): string {
  if (!text) return "";
  return text.replace(/\[([^:]+):[^\]]+\]/g, "$1");
}
