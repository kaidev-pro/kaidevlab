/**
 * Automatically annotates plain Japanese text with bracket furigana syntax: [kanji:furigana]
 * If text already contains bracket ruby syntax, it leaves existing ones intact.
 */
export function autoAnnotateRuby(text: string): string {
  if (!text) return "";

  // If already heavily annotated, return as-is
  if (text.includes("[") && text.includes(":") && text.includes("]")) {
    return text;
  }

  let result = text;

  // Replace each known term with its ruby bracket annotation
  for (const [kanji, ruby] of FE_KANJI_DICT) {
    if (result.includes(kanji)) {
      // Use split and join to replace all occurrences without regex escaping issues
      result = result.split(kanji).join(ruby);
    }
  }

  return result;
}

/**
 * Strips all bracket ruby annotations like "[公開鍵:こうかいかぎ]"
 * back into plain text "公開鍵" for speech synthesis (TTS) or search.
 */
export function stripRuby(text: string): string {
  if (!text) return "";
  return text.replace(/\[([^:]+):[^\]]+\]/g, "$1");
}
